#!/bin/bash

# 西安高铁最短路径查询系统演示脚本

echo "=========================================="
echo "西安高铁最短路径查询系统演示"
echo "=========================================="
echo ""

# 编译程序
echo "1. 编译程序..."
make clean > /dev/null 2>&1
make > /dev/null 2>&1
if [ $? -ne 0 ]; then
    echo "编译失败！"
    exit 1
fi
echo "   编译成功！"
echo ""

# 显示帮助信息
echo "2. 显示帮助信息..."
echo "-------------------------------------------"
./railway -h
echo ""

# 列出所有站点
echo "3. 列出所有站点（前20个）..."
echo "-------------------------------------------"
./railway -l | head -20
echo "..."
echo ""

# 查询西安到成都
echo "4. 查询西安到成都的最短路径..."
echo "-------------------------------------------"
./railway -f 西安 成都
echo ""

# 查询西安到上海
echo "5. 查询西安到上海的最短路径..."
echo "-------------------------------------------"
./railway -f 西安 上海虹桥
echo ""

# 查询西安到北京
echo "6. 查询西安到北京的最短路径..."
echo "-------------------------------------------"
./railway -f 西安 北京西
echo ""

# 查询西安到广州
echo "7. 查询西安到广州的最短路径..."
echo "-------------------------------------------"
./railway -f 西安 广州南
echo ""

# 查询西安到昆明
echo "8. 查询西安到昆明的最短路径..."
echo "-------------------------------------------"
./railway -f 西安 昆明南
echo ""

# 显示从西安到所有站点的路径（前30个）
echo "9. 显示从西安到所有站点的最短路径（前30个）..."
echo "-------------------------------------------"
./railway -a | head -30
echo "..."
echo ""

echo "=========================================="
echo "演示完成！"
echo "=========================================="
echo ""
echo "使用方法:"
echo "  ./railway -a              # 从西安到所有站点"
echo "  ./railway -f 西安 成都     # 西安到成都"
echo "  ./railway -s 北京          # 从北京出发"
echo "  ./railway -l              # 列出所有站点"
echo "  ./railway -h              # 显示帮助"
